setup_repository() {
  local case_dir=$1; shift
  local remote=$case_dir/remote.git work=$case_dir/work
  mkdir -p "$case_dir"
  "$real_git" init --bare --initial-branch=main "$remote" >/dev/null
  "$real_git" clone "$remote" "$work" >/dev/null 2>&1
  (
    cd "$work"
    "$real_git" config user.name test
    "$real_git" config user.email test@example.com
    echo base > base.txt
    "$real_git" add base.txt
    "$real_git" commit -m base >/dev/null
    "$real_git" push -u origin main >/dev/null

    local previous=main index=0 id token
    for id in "$@"; do
      index=$((index + 1))
      "$real_git" checkout -b "$id" "$previous" >/dev/null
      echo "$id" > "change-$index.txt"
      "$real_git" add "change-$index.txt"
      token=gherrit-pr-id
      if [[ $id == "$legacy_g" ]]; then token=GHERRIT-PR-ID; fi
      if [[ $id == "$legacy_i" ]]; then token=GhErRiT-Pr-Id; fi
      "$real_git" commit -m "change $index" -m "$token: $id" >/dev/null
      "$real_git" tag "gherrit/$id/v1"
      "$real_git" push origin "$id" "refs/tags/gherrit/$id/v1" >/dev/null
      previous=$id
    done
  )
}

initialize_state() {
  local work=$1 state=$2; shift 2
  local ids=("$@")
  printf '{"prs":[' > "$state"
  local index id parent child comma= number
  for ((index=0; index<${#ids[@]}; index++)); do
    id=${ids[$index]}
    parent=
    child=
    (( index > 0 )) && parent=${ids[$((index - 1))]}
    (( index + 1 < ${#ids[@]} )) && child=${ids[$((index + 1))]}
    body=$(body_for "$id" "$parent" "$child")
    head_oid=$("$real_git" -C "$work" rev-parse "$id")
    number=$((index + 1))
    printf '%s' "$comma" >> "$state"
    jq -cn \
      --arg id "PR_$number" --argjson number "$number" \
      --arg head "$id" --arg head_oid "$head_oid" \
      --arg base "${parent:-main}" --arg body "$body" \
      '{id:$id,number:$number,head:$head,head_oid:$head_oid,base:$base,body:$body,merged:false,queue:false,auto:false,stack:false}' \
      >> "$state"
    comma=,
  done
  printf ']}' >> "$state"
}

merge_equivalent() {
  local work=$1 id=$2 shape=$3
  (
    cd "$work"
    "$real_git" checkout main >/dev/null
    "$real_git" fetch origin main >/dev/null
    "$real_git" reset --hard origin/main >/dev/null
    case "$shape" in
      squash)
        "$real_git" merge --squash "$id" >/dev/null
        "$real_git" commit -m "squash $id" >/dev/null
        ;;
      rebase)
        "$real_git" cherry-pick --no-commit "$id" >/dev/null
        "$real_git" commit -m "rebase-merged $id" >/dev/null
        ;;
      fast-forward)
        "$real_git" merge --ff-only "$id" >/dev/null
        ;;
      *) echo "unknown merge shape '$shape'" >&2; return 1 ;;
    esac
    "$real_git" push origin main >/dev/null
  )
}

mark_merged() {
  local state=$1 id=$2
  local body
  body=$(jq -er --arg id "$id" '.prs[] | select(.head == $id) | .body' "$state")
  tmp=$state.tmp
  jq --arg id "$id" '.prs |= map(if .head == $id then .merged = true | .base = "main" else . end)' "$state" > "$tmp"
  mv "$tmp" "$state"
  printf '%s' "$body"
}

run_action() {
  local work=$1 state=$2 merged_id=$3 merged_number=$4 merged_body=$5
  (
    cd "$work"
    export REAL_GIT="$real_git"
    export PATH="$TEST_BIN:$PATH"
    export ACTION_PATH="$repo_root"
    export GH_TOKEN=test-token
    export MERGED_PR_BODY="$merged_body"
    export MERGED_PR_NUMBER="$merged_number"
    export MERGED_PR_HEAD="$merged_id"
    export MERGED_PR_BASE=main
    export MERGED_HEAD_REPOSITORY_ID="$repository_id"
    export MERGED_BASE_REPOSITORY_ID="$repository_id"
    export DEFAULT_BRANCH=main
    export TARGET_REPOSITORY="$repository_name"
    export TARGET_REPOSITORY_ID="$repository_id"
    export TEST_STATE="$state"
    export TEST_REMOTE="$TEST_REMOTE"
    bash "$repo_root/ci/cascade_stack.sh"
  )
}

assert_promoted() {
  local remote=$1 state=$2 id=$3 expected_version=$4
  local head main body
  head=$("$real_git" --git-dir="$remote" rev-parse "refs/heads/$id")
  main=$("$real_git" --git-dir="$remote" rev-parse refs/heads/main)
  if [[ $head == "$main" ]]; then
    echo "promoted child '$id' equals the default branch" >&2
    exit 1
  fi
  if [[ $("$real_git" --git-dir="$remote" rev-parse "$head^") != "$main" ]]; then
    echo "promoted child '$id' is not directly based on main" >&2
    exit 1
  fi
  if [[ $("$real_git" --git-dir="$remote" rev-parse "refs/tags/gherrit/$id/v$expected_version") != "$head" ]]; then
    echo "promoted child '$id' lacks version v$expected_version at its head" >&2
    exit 1
  fi
  if [[ $(jq -er --arg id "$id" '.prs[] | select(.head == $id) | .base' "$state") != main ]]; then
    echo "promoted child '$id' did not target main" >&2
    exit 1
  fi
  body=$(jq -er --arg id "$id" '.prs[] | select(.head == $id) | .body' "$state")
  if [[ $(printf '%s' "$body" | bash "$repo_root/ci/extract_stack_metadata.sh" | jq -r '.parent // ""') != "" ]]; then
    echo "promoted child '$id' retained parent metadata" >&2
    exit 1
  fi
}

test_group=${CASCADE_TEST_GROUP:-all}
run_group() {
  [[ $test_group == all || $test_group == "$1" ]]
}

run_basic_case() {
  local shape=$1 parent_deleted=$2 child_id=${3:-$current_b}
  local case_dir=$root/basic-$shape-$parent_deleted-$child_id
  local remote=$case_dir/remote.git work=$case_dir/work state=$case_dir/state.json
  setup_repository "$case_dir" "$current_a" "$child_id"
  initialize_state "$work" "$state" "$current_a" "$child_id"
  merge_equivalent "$work" "$current_a" "$shape"
  merged_body=$(mark_merged "$state" "$current_a")
  if [[ $parent_deleted == true ]]; then "$real_git" --git-dir="$remote" update-ref -d "refs/heads/$current_a"; fi
  if [[ $parent_deleted == true ]]; then
    tmp=$state.tmp
    jq --arg id "$child_id" '.prs |= map(if .head == $id then .base = "main" else . end)' "$state" > "$tmp" && mv "$tmp" "$state"
  fi
  TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
  export TEST_BIN TEST_REMOTE TEST_PUSH_MODE=none TEST_UPDATE_MODE=none
  write_fake_tools "$TEST_BIN"
  run_action "$work" "$state" "$current_a" 1 "$merged_body"
  assert_promoted "$remote" "$state" "$child_id" 2
}

if run_group basic || run_group basic-parent; then
  run_basic_case squash false
fi
if run_group basic || run_group basic-auto; then
  run_basic_case squash true
fi
if run_group basic || run_group basic-rebase; then
  run_basic_case rebase true
fi
if run_group basic || run_group legacy; then
  run_basic_case squash false "$legacy_g"
  run_basic_case squash false "$legacy_i"
fi

# A three-PR stack must cascade twice. The first promotion rewrites B metadata
# to a root, and the second merged event can therefore authenticate B -> C.
if run_group two-hop; then
  case_dir=$root/two-hop
  remote=$case_dir/remote.git; work=$case_dir/work; state=$case_dir/state.json
  setup_repository "$case_dir" "$current_a" "$current_b" "$current_c"
  initialize_state "$work" "$state" "$current_a" "$current_b" "$current_c"
  merge_equivalent "$work" "$current_a" squash
  merged_body=$(mark_merged "$state" "$current_a")
  TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
  export TEST_BIN TEST_REMOTE TEST_PUSH_MODE=none TEST_UPDATE_MODE=none
  write_fake_tools "$TEST_BIN"
  run_action "$work" "$state" "$current_a" 1 "$merged_body"
  assert_promoted "$remote" "$state" "$current_b" 2
  merge_equivalent "$work" "$current_b" squash
  merged_body=$(mark_merged "$state" "$current_b")
  run_action "$work" "$state" "$current_b" 2 "$merged_body"
  assert_promoted "$remote" "$state" "$current_c" 2
fi

# Rebase conflict and a pre-application push failure must leave the PR base and
# remote branch untouched while the parent ref is retained.
if run_group pre-publish-failures; then
  for failure in conflict push-before; do
    case_dir=$root/$failure
    remote=$case_dir/remote.git; work=$case_dir/work; state=$case_dir/state.json
    setup_repository "$case_dir" "$current_a" "$current_b"
    initialize_state "$work" "$state" "$current_a" "$current_b"
    old_head=$("$real_git" --git-dir="$remote" rev-parse "refs/heads/$current_b")
    if [[ $failure == conflict ]]; then
      (
        cd "$work"
        "$real_git" checkout main >/dev/null
        echo main > change-2.txt
        "$real_git" add change-2.txt
        "$real_git" commit -m conflicting-main >/dev/null
        "$real_git" push origin main >/dev/null
      )
    else
      merge_equivalent "$work" "$current_a" squash
    fi
    merged_body=$(mark_merged "$state" "$current_a")
    TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
    export TEST_BIN TEST_REMOTE TEST_UPDATE_MODE=none
    if [[ $failure == push-before ]]; then export TEST_PUSH_MODE=before; else export TEST_PUSH_MODE=none; fi
    write_fake_tools "$TEST_BIN"
    if run_action "$work" "$state" "$current_a" 1 "$merged_body" >/dev/null 2>&1; then
      echo "$failure cascade unexpectedly succeeded" >&2; exit 1
    fi
    [[ $(jq -er --arg id "$current_b" '.prs[] | select(.head == $id) | .base' "$state") == "$current_a" ]]
    [[ $("$real_git" --git-dir="$remote" rev-parse "refs/heads/$current_b") == "$old_head" ]]
  done
fi

# Lost acknowledgements after the atomic push or PR update are reconciled by
# observing the exact durable result.
if run_group ambiguous-success; then
  for failure in push-after update-after; do
    case_dir=$root/$failure
    remote=$case_dir/remote.git; work=$case_dir/work; state=$case_dir/state.json
    setup_repository "$case_dir" "$current_a" "$current_b"
    initialize_state "$work" "$state" "$current_a" "$current_b"
    merge_equivalent "$work" "$current_a" squash
    merged_body=$(mark_merged "$state" "$current_a")
    TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
    export TEST_BIN TEST_REMOTE TEST_PUSH_MODE=none TEST_UPDATE_MODE=none
    [[ $failure == push-after ]] && export TEST_PUSH_MODE=after
    [[ $failure == update-after ]] && export TEST_UPDATE_MODE=after
    write_fake_tools "$TEST_BIN"
    run_action "$work" "$state" "$current_a" 1 "$merged_body"
    assert_promoted "$remote" "$state" "$current_b" 2
  done
fi

# A lost/not-applied PR edit after successful Git publication is retryable even
# when the parent branch is retained.
if run_group projection-retry; then
  case_dir=$root/update-before
  remote=$case_dir/remote.git; work=$case_dir/work; state=$case_dir/state.json
  setup_repository "$case_dir" "$current_a" "$current_b"
  initialize_state "$work" "$state" "$current_a" "$current_b"
  merge_equivalent "$work" "$current_a" squash
  merged_body=$(mark_merged "$state" "$current_a")
  TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
  export TEST_BIN TEST_REMOTE TEST_PUSH_MODE=none TEST_UPDATE_MODE=before
  write_fake_tools "$TEST_BIN"
  if run_action "$work" "$state" "$current_a" 1 "$merged_body" >/dev/null 2>&1; then
    echo "pre-application update failure unexpectedly succeeded" >&2; exit 1
  fi
  [[ $(jq -er --arg id "$current_b" '.prs[] | select(.head == $id) | .base' "$state") == "$current_a" ]]
  export TEST_UPDATE_MODE=none
  run_action "$work" "$state" "$current_a" 1 "$merged_body"
  assert_promoted "$remote" "$state" "$current_b" 2
fi

# Operational blockers are checked before checkout, rebase, push, or retarget.
run_blocker_case() {
  local blocker=$1
  case_dir=$root/blocker-$blocker
  remote=$case_dir/remote.git; work=$case_dir/work; state=$case_dir/state.json
  setup_repository "$case_dir" "$current_a" "$current_b"
  initialize_state "$work" "$state" "$current_a" "$current_b"
  merge_equivalent "$work" "$current_a" squash
  merged_body=$(mark_merged "$state" "$current_a")
  tmp=$state.tmp
  jq --arg id "$current_b" --arg blocker "$blocker" '
    .prs |= map(
      if .head == $id then
        .auto = ($blocker == "auto") |
        .queue = ($blocker == "queue") |
        .stack = ($blocker == "stack")
      else . end
    )
  ' "$state" > "$tmp" && mv "$tmp" "$state"
  old_head=$("$real_git" --git-dir="$remote" rev-parse "refs/heads/$current_b")
  TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
  export TEST_BIN TEST_REMOTE TEST_PUSH_MODE=none TEST_UPDATE_MODE=none
  write_fake_tools "$TEST_BIN"
  if run_action "$work" "$state" "$current_a" 1 "$merged_body" >/dev/null 2>&1; then
    echo "$blocker cascade unexpectedly succeeded" >&2; exit 1
  fi
  [[ $("$real_git" --git-dir="$remote" rev-parse "refs/heads/$current_b") == "$old_head" ]]
  [[ $(jq -er --arg id "$current_b" '.prs[] | select(.head == $id) | .base' "$state") == "$current_a" ]]
}

if run_group blockers || run_group blocker-auto; then
  run_blocker_case auto
fi
if run_group blockers || run_group blocker-queue; then
  run_blocker_case queue
fi
if run_group blockers || run_group blocker-stack; then
  run_blocker_case stack
fi

# If the child patch is already represented upstream, --empty=keep must still
# preserve a distinct authenticated child commit rather than pushing main.
if run_group empty-child; then
  case_dir=$root/empty-child
  remote=$case_dir/remote.git; work=$case_dir/work; state=$case_dir/state.json
  setup_repository "$case_dir" "$current_a" "$current_b"
  initialize_state "$work" "$state" "$current_a" "$current_b"
  (
    cd "$work"
    "$real_git" checkout main >/dev/null
    "$real_git" cherry-pick --no-commit "$current_a" >/dev/null
    "$real_git" cherry-pick --no-commit "$current_b" >/dev/null
    "$real_git" commit -m 'land parent and child equivalents' >/dev/null
    "$real_git" push origin main >/dev/null
  )
  merged_body=$(mark_merged "$state" "$current_a")
  TEST_BIN=$case_dir/bin TEST_REMOTE=$remote
  export TEST_BIN TEST_REMOTE TEST_PUSH_MODE=none TEST_UPDATE_MODE=none
  write_fake_tools "$TEST_BIN"
  run_action "$work" "$state" "$current_a" 1 "$merged_body"
  assert_promoted "$remote" "$state" "$current_b" 2
  child_head=$("$real_git" --git-dir="$remote" rev-parse "refs/heads/$current_b")
  main_head=$("$real_git" --git-dir="$remote" rev-parse refs/heads/main)
  [[ $("$real_git" --git-dir="$remote" rev-parse "$child_head^{tree}") == $("$real_git" --git-dir="$remote" rev-parse "$main_head^{tree}") ]]
fi
