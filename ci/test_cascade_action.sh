#!/usr/bin/env bash

set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
root=$(mktemp -d)
trap 'rm -rf "$root"' EXIT
real_git=$(command -v git)
repository_id=R_target_repository
repository_name=owner/repository

current_a=Gbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb
current_b=Gaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
current_c=Gcccccccccccccccccccccccccccccccc
legacy_g=G0123456789abcdef0123456789abcdef01234567
legacy_i=I0123456789abcdef0123456789abcdef01234567

body_for() {
  local id=$1 parent=$2 child=$3
  local parent_json child_json
  if [[ -n $parent ]]; then parent_json=\"$parent\"; else parent_json=null; fi
  if [[ -n $child ]]; then child_json=\"$child\"; else child_json=null; fi
  cat <<EOF
<!-- WARNING: This PR description is automatically generated by GHerrit. Any manual edits will be overwritten on the next push. -->

Test PR body.

---

- 👉 #1

<details>
<summary><strong>⬇️ Download this PR</strong></summary>

######

</details>

*Stacked PRs enabled by [GHerrit](https://github.com/joshlf/gherrit).*

<!-- WARNING: GHerrit relies on the following metadata to work properly. DO NOT EDIT OR REMOVE. --><!-- gherrit-meta: {"id":"$id","parent":$parent_json,"child":$child_json} -->
EOF
}

write_fake_tools() {
  local bin=$1
  mkdir -p "$bin"
  cat > "$bin/gh" <<'GH'
